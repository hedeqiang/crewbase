// registerMediaListener files every generated image and video.
func registerMediaListener(c *kernel.Context, s *Service, teamOf func(string) string, file func(string, AddRequest)) {
	media.Created.Listen(c, func(m media.CreatedFile) {
		data, err := os.ReadFile(filepath.Join(m.Workspace, filepath.FromSlash(m.Saved.Path)))
		if err != nil {
			return
		}
		file("a generated "+m.Kind, AddRequest{Team: teamOf(m.Agent), Folder: FolderMedia, Name: filepath.Base(m.Saved.Path),
			Data: data, Source: SourceGenerated, Agent: m.Agent, Session: m.Session, Note: m.Prompt})
	})
}

func describe(it Item) string {
	var b strings.Builder
	fmt.Fprintf(&b, "[%d] %s/%s", it.ID, it.Folder, it.Name)
	if it.Title != "" && it.Title != it.Name {
		fmt.Fprintf(&b, " — %s", it.Title)
	}
	fmt.Fprintf(&b, " · %s · %s", humanSize(it.Size), it.Updated.Local().Format("2006-01-02"))
	switch it.Source {
	case SourceUpload:
		b.WriteString(" · uploaded by the person")
	case SourceGenerated:
		fmt.Fprintf(&b, " · generated by %s", it.Agent)
	case SourceAgent:
		fmt.Fprintf(&b, " · saved by %s", it.Agent)
	}
	if len(it.Tags) > 0 {
		fmt.Fprintf(&b, " · tags: %s", strings.Join(it.Tags, ", "))
	}
	if it.Private {
		b.WriteString(" · private")
	}
	return b.String()
}

func humanSize(n int64) string {
	switch {
	case n < 1024:
		return fmt.Sprintf("%d B", n)
	case n < 1<<20:
		return fmt.Sprintf("%.0f KB", float64(n)/1024)
	}
	return fmt.Sprintf("%.1f MB", float64(n)/(1<<20))
}

func registerTools(c *kernel.Context, s *Service, agents *agent.Registry) {
	reg := kernel.Use[*tools.Registry](c, tools.ServiceKey)
	viewer := func(call tools.Call) (Viewer, error) {
		a, ok := agents.Get(call.Agent)
		if !ok {
			return Viewer{}, errors.New("the library is for agents")
		}
		return Viewer{Team: a.Spec().TeamID(), Agent: a.ID()}, nil
	}

	reg.Register(c, &tools.Tool{
		Name: "library_search",
		Description: "Search the team's document library (文档库): files the person uploaded, images and videos agents generated, and documents agents saved. " +
			"It matches names, titles, tags and the text inside PDFs, Word, Excel, PowerPoint and text files. Use it when the person refers to a document, " +
			"a file they sent before, or earlier work you cannot see in this conversation. An empty query lists the newest documents.",
		Params: tools.Schema(map[string]any{
			"query":  tools.Prop("string", "words to find (any language); empty: the newest documents"),
			"folder": tools.Prop("string", "only inbox (uploads), media (images, videos), docs or pages"),
			"limit":  tools.Prop("integer", "how many results (default 10, at most 50)"),
		}),
		Category: tools.CategoryRead,
		Execute: func(ctx context.Context, call tools.Call) (tools.Result, error) {
			var args struct {
				Query  string `json:"query"`
				Folder string `json:"folder"`
				Limit  int    `json:"limit"`
			}
			if err := call.Decode(&args); err != nil {
				return tools.Errorf("invalid arguments: %v", err), nil
			}
			v, err := viewer(call)
			if err != nil {
				return tools.Errorf("%v", err), nil
			}
			hits, err := s.Search(ctx, v, args.Query, args.Limit)
			if err != nil {
				return tools.Errorf("library_search: %v", err), nil
			}
			if args.Folder != "" {
				keep := hits[:0]
				for _, h := range hits {
					if h.Folder == args.Folder {
						keep = append(keep, h)
					}
				}
				hits = keep
			}
			if len(hits) == 0 {
				return tools.Text("Nothing in the library matches. (Files the person uploads and documents saved with library_save land there.)"), nil
			}
			var b strings.Builder
			for _, h := range hits {
				b.WriteString(describe(h.Item))
				if h.Snippet != "" {
					b.WriteString("\n    " + strings.ReplaceAll(strings.TrimSpace(h.Snippet), "\n", " "))
				}
				b.WriteString("\n")
			}
			b.WriteString("Read one with library_read {id}.")
			return tools.Result{Content: b.String(), Data: hits}, nil
		},
	})

	reg.Register(c, &tools.Tool{
		Name: "library_read",
		Description: "Read a document of the library by its id (from library_search): its text (extracted from PDF, Word, Excel, PowerPoint), " +
			"or copy the file into your workspace with copy_to to work on it (e.g. edit a spreadsheet, process an image).",
		Params: tools.Schema(map[string]any{
			"id":      tools.Prop("integer", "the document id"),
			"from":    tools.Prop("integer", "start at this character of the text (to continue a long one)"),
			"copy_to": tools.Prop("string", "copy the file to this path in your workspace instead of returning its text"),
		}, "id"),
		Category: tools.CategoryRead,
		Load:     tools.LoadDeferred,
		Group:    "library",
		Execute: func(ctx context.Context, call tools.Call) (tools.Result, error) {
			var args struct {
				ID     int64  `json:"id"`
				From   int    `json:"from"`
				CopyTo string `json:"copy_to"`
			}
			if err := call.Decode(&args); err != nil {
				return tools.Errorf("invalid arguments: %v", err), nil
			}
			v, err := viewer(call)
			if err != nil {
				return tools.Errorf("%v", err), nil
			}
			it, err := s.Get(v, args.ID)
			if err != nil {
				return tools.Errorf("library_read: %v", err), nil
			}
			if args.CopyTo != "" {
				dst, err := inside(call.Workspace, args.CopyTo)
				if err != nil {
					return tools.Errorf("copy_to: %v", err), nil
				}
				data, err := os.ReadFile(s.File(it))
				if err != nil {
					return tools.Errorf("library_read: %v", err), nil
				}
				if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
					return tools.Errorf("copy_to: %v", err), nil
				}
				if err := os.WriteFile(dst, data, 0o644); err != nil {
					return tools.Errorf("copy_to: %v", err), nil
				}
				return tools.Text(fmt.Sprintf("Copied %s (%s) to %s.", it.Name, humanSize(it.Size), args.CopyTo)), nil
			}
			s.drain(ctx, 20*time.Second) // a document added a moment ago
			if it, err = s.Get(v, args.ID); err != nil {
				return tools.Errorf("library_read: %v", err), nil
			}
			text := s.Body(it.ID)
			var b strings.Builder
			b.WriteString(describe(it) + "\n")
			if it.Note != "" {
				b.WriteString("Prompt / note: " + it.Note + "\n")
			}
			switch {
			case !it.Text && (strings.HasPrefix(it.Mime, "image/") || strings.HasPrefix(it.Mime, "video/")):
				b.WriteString("\nThis is an image or video; its content is not text. Use copy_to to put it in your workspace and look at it.")
				return tools.Text(b.String()), nil
			case text == "":
				b.WriteString("\nNo text could be read from this file. Use copy_to to work on the file itself.")
				return tools.Text(b.String()), nil
			}
			r := []rune(text)
			from := min(max(args.From, 0), len(r))
			to := min(from+maxReadChars, len(r))
			b.WriteString("\n" + string(r[from:to]))
			if to < len(r) {
				fmt.Fprintf(&b, "\n\n[%d of %d characters shown; continue with from: %d]", to-from, len(r), to)
			}
			return tools.Text(b.String()), nil
		},
	})

	reg.Register(c, &tools.Tool{
		Name: "library_save",
		Description: "Keep a document in the team's library so the person and other agents can find it later: a report, plan, summary or other result " +
			"worth keeping (not scratch files). Give either a file path in your workspace, or a name and its content. Saving again with the same name " +
			"in the same folder replaces it and keeps the earlier content as a version.",
		Params: tools.Schema(map[string]any{
			"path":    tools.Prop("string", "a file in your workspace to keep"),
			"name":    tools.Prop("string", "the document's file name, e.g. 竞品分析.md (with content, or to rename path)"),
			"content": tools.Prop("string", "the document's text, instead of path"),
			"title":   tools.Prop("string", "a short title"),
			"tags":    map[string]any{"type": "array", "items": map[string]any{"type": "string"}, "description": "tags, e.g. a project name"},
			"private": tools.Prop("boolean", "only you can see it (default: the whole team)"),
		}),
		Category: tools.CategoryWrite,
		Load:     tools.LoadDeferred,
		Group:    "library",
		Execute: func(ctx context.Context, call tools.Call) (tools.Result, error) {
			var args struct {
				Path    string   `json:"path"`
				Name    string   `json:"name"`
				Content *string  `json:"content"`
				Title   string   `json:"title"`
				Tags    []string `json:"tags"`
				Private bool     `json:"private"`
			}
			if err := call.Decode(&args); err != nil {
				return tools.Errorf("invalid arguments: %v", err), nil
			}
			v, err := viewer(call)
			if err != nil {
				return tools.Errorf("%v", err), nil
			}
			var data []byte
			name := strings.TrimSpace(args.Name)
			switch {
			case args.Path != "" && args.Content != nil:
				return tools.Errorf("give path or content, not both"), nil
			case args.Path != "":
				p, err := inside(call.Workspace, args.Path)
				if err != nil {
					return tools.Errorf("path: %v", err), nil
				}
				if data, err = os.ReadFile(p); err != nil {
					return tools.Errorf("library_save: %v", err), nil
				}
				if name == "" {
					name = filepath.Base(p)
				}
			case args.Content != nil:
				if name == "" {
					return tools.Errorf("content needs a name, e.g. 方案.md"), nil
				}
				if !strings.Contains(name, ".") {
					name += ".md"
				}
				data = []byte(*args.Content)
			default:
				return tools.Errorf("give path (a file in your workspace) or name and content"), nil
			}
			if !utf8.Valid(data[:min(len(data), 512)]) && args.Content != nil {
				return tools.Errorf("content must be text"), nil
			}
			sid := ""
			if call.Session != nil {
				sid = call.Session.ID()
			}
			it, err := s.Add(ctx, AddRequest{Team: v.Team, Name: name, Title: args.Title, Data: data, Source: SourceAgent, Agent: v.Agent,
				Session: sid, Tags: args.Tags, Private: args.Private, Replace: true})
			if err != nil {
				return tools.Errorf("library_save: %v", err), nil
			}
			msg := fmt.Sprintf("Saved to the library: %s", describe(it))
			if it.Versions > 0 {
				msg += fmt.Sprintf(" (replaced it; %d earlier version(s) kept)", it.Versions)
			}
			return tools.Result{Content: msg, Data: it}, nil
		},
	})
}

// inside resolves p (relative or absolute) within the workspace.
func inside(ws, p string) (string, error) {
	if ws == "" {
		return "", errors.New("no workspace")
	}
	if !filepath.IsAbs(p) {
		p = filepath.Join(ws, p)
	}
	p = filepath.Clean(p)
	rel, err := filepath.Rel(ws, p)
	if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("must be inside your workspace")
	}
	return p, nil
}
