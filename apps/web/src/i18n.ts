export type Lang = "zh" | "en";
const LANG_KEY = "crewbase.lang";

// the person's choice; otherwise the system's language (Chinese systems get
// Chinese, everything else English)
let lang: Lang = (() => {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "zh" || v === "en") return v;
  } catch {
    /* ignore */
  }
  const sys = (typeof navigator !== "undefined" && (navigator.languages?.[0] || navigator.language)) || "zh";
  return /^zh\b/i.test(sys) ? "zh" : "en";
})();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
  // the desktop shell's menus and tray follow
  try {
    (window as { crewbaseDesktop?: { setLanguage?: (l: string) => void } }).crewbaseDesktop?.setLanguage?.(l);
  } catch {
    /* not in the desktop app */
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = (lang === "en" && en[key]) || zh[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
